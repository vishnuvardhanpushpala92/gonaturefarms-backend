package com.gonaturefarms.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * One-time-safe migration: the production orders table has CHECK constraints
 * (orders_payment_status_check / orders_status_check) created before the
 * VerificationPending / PaymentVerificationPending statuses existed.
 * ddl-auto=update does not manage CHECK constraints, so we repair them here
 * on every startup (idempotent — safe to re-run).
 */
@Component
public class DbConstraintMigration implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(DbConstraintMigration.class);

    private final JdbcTemplate jdbcTemplate;

    public DbConstraintMigration(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @Override
    public void run(ApplicationArguments args) {
        // Prod runs ddl-auto=validate, so entity columns are never auto-added.
        // Add return_eligible to products (idempotent). Default TRUE preserves
        // the pre-existing behavior where returns were allowed for all products.
        // Prod runs ddl-auto=validate, so new entity tables are never auto-created.
        // Entity uses GenerationType.IDENTITY → id must be an identity column.
        // The table is empty (all prior saves failed), so recreate it correctly.
        try {
            jdbcTemplate.execute("DROP TABLE IF EXISTS support_settings");
            jdbcTemplate.execute(
                "CREATE TABLE support_settings (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "support_phone VARCHAR(20), " +
                "whatsapp_number VARCHAR(20), " +
                "whatsapp_country_code VARCHAR(10) DEFAULT '91', " +
                "support_email VARCHAR(100), " +
                "business_hours VARCHAR(200), " +
                "working_days VARCHAR(100), " +
                "store_address TEXT, " +
                "whatsapp_welcome_message TEXT, " +
                "response_info TEXT, " +
                "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, " +
                "updated_at TIMESTAMP)");
            log.info("support_settings table ensured");
        } catch (Exception e) {
            log.error("Failed to create support_settings: {}", e.getMessage());
        }

        try {
            jdbcTemplate.execute("ALTER TABLE products ADD COLUMN IF NOT EXISTS return_eligible BOOLEAN NOT NULL DEFAULT TRUE");
            log.info("products.return_eligible column ensured");
        } catch (Exception e) {
            log.error("Failed to add products.return_eligible: {}", e.getMessage());
        }

        try {
            jdbcTemplate.execute("ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_payment_status_check");
            jdbcTemplate.execute("ALTER TABLE orders ADD CONSTRAINT orders_payment_status_check " +
                    "CHECK (payment_status IN ('Pending','VerificationPending','Paid','Failed','Refunded','Cancelled'))");
            log.info("orders_payment_status_check constraint updated");
        } catch (Exception e) {
            log.error("Failed to update orders_payment_status_check: {}", e.getMessage());
        }

        try {
            jdbcTemplate.execute("ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check");
            jdbcTemplate.execute("ALTER TABLE orders ADD CONSTRAINT orders_status_check " +
                    "CHECK (status IN ('Pending','Placed','Confirmed','Processing','Packed','Shipped','OutForDelivery','Delivered','Cancelled','PaymentVerificationPending'))");
            log.info("orders_status_check constraint updated");
        } catch (Exception e) {
            log.error("Failed to update orders_status_check: {}", e.getMessage());
        }

        // Complaint inbox columns on support_tickets (entity fields added for complaints).
        try {
            jdbcTemplate.execute("ALTER TABLE support_tickets ADD COLUMN IF NOT EXISTS customer_name VARCHAR(120)");
            jdbcTemplate.execute("ALTER TABLE support_tickets ADD COLUMN IF NOT EXISTS customer_mobile VARCHAR(20)");
            jdbcTemplate.execute("ALTER TABLE support_tickets ADD COLUMN IF NOT EXISTS customer_email VARCHAR(120)");
            jdbcTemplate.execute("ALTER TABLE support_tickets ADD COLUMN IF NOT EXISTS customer_response TEXT");
            jdbcTemplate.execute("ALTER TABLE support_tickets DROP CONSTRAINT IF EXISTS support_tickets_status_check");
            jdbcTemplate.execute("ALTER TABLE support_tickets ADD CONSTRAINT support_tickets_status_check " +
                    "CHECK (status IN ('open','pending','in_progress','resolved','rejected'))");
            log.info("support_tickets complaint columns ensured");
        } catch (Exception e) {
            log.error("Failed to add support_tickets complaint columns: {}", e.getMessage());
        }

        // whatsapp_reminders: entity maps updated_at but older prod table lacks it.
        try {
            jdbcTemplate.execute("CREATE TABLE IF NOT EXISTS whatsapp_reminders (" +
                "id BIGSERIAL PRIMARY KEY, admin_id BIGINT NOT NULL, reminder_type VARCHAR(50) NOT NULL, " +
                "product_id BIGINT, message TEXT NOT NULL, scheduled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, " +
                "sent_at TIMESTAMP, status VARCHAR(20) DEFAULT 'Pending', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, " +
                "updated_at TIMESTAMP)");
            jdbcTemplate.execute("ALTER TABLE whatsapp_reminders ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP");
            jdbcTemplate.execute("ALTER TABLE whatsapp_reminders ADD COLUMN IF NOT EXISTS product_id BIGINT");
            log.info("whatsapp_reminders columns ensured");
        } catch (Exception e) {
            log.error("Failed to ensure whatsapp_reminders columns: {}", e.getMessage());
        }

        try {
            jdbcTemplate.execute(
                "CREATE TABLE IF NOT EXISTS admin_audit_log (" +
                "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "admin_id BIGINT, admin_name VARCHAR(120), action VARCHAR(60) NOT NULL, " +
                "details TEXT, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)");
            log.info("admin_audit_log table ensured");
        } catch (Exception e) {
            log.error("Failed to create admin_audit_log: {}", e.getMessage());
        }
    }
}
